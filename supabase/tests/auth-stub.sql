-- Test-only: the pieces of the `auth` schema that Supabase Auth (GoTrue)
-- creates on a hosted project but the bare supabase/postgres image lacks.
-- Run as supabase_admin BEFORE the migrations when testing against a plain
-- container (scripts/test-db.sh does this). Never run against production.

alter table auth.users add column if not exists email_confirmed_at timestamptz;

create or replace function auth.jwt()
returns jsonb
language sql
stable
as $$
  select coalesce(
    nullif(current_setting('request.jwt.claim', true), ''),
    nullif(current_setting('request.jwt.claims', true), '')
  )::jsonb
$$;

grant execute on function auth.jwt() to anon, authenticated, service_role;

-- Modern GoTrue versions read the claims JSON (the image ships legacy ones).
create or replace function auth.uid()
returns uuid
language sql
stable
as $$
  select coalesce(
    nullif(current_setting('request.jwt.claim.sub', true), ''),
    nullif(current_setting('request.jwt.claims', true), '')::jsonb ->> 'sub'
  )::uuid
$$;

create or replace function auth.role()
returns text
language sql
stable
as $$
